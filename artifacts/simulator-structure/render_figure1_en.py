"""Figure 1 of the Methods: one wave in Rippletown (no director).

Order follows the wave loop in ABM/simulation/runner.py: scheduled events, state
endings, concurrent agent turns, routing by start-of-wave positions, applying
requests, advancing the clock, then contact processes.
"""
from render import Diagram, INK, MUTED, TEAL, ORANGE
from render_infection_en_v2 import pill, LLM_C, LLM_FILL, ENG_FILL, ORANGE_FILL, RULE

W, H = 370, 214
XS = [70 + i * 415 for i in range(4)]
ROW_A, ROW_B = 170, 490


def step(d, x, y, number, title, lines, tag, color=TEAL, badge=ENG_FILL):
    d.rect(x, y, W, H, 'white', RULE, 19)
    d.rect(x + 20, y + 20, 42, 38, badge, badge, 10, 1)
    d.text(x + 33, y + 48, str(number), 23, color, True)
    if tag == 'LLM':
        pill(d, x + W - 78, y + 25, 'LLM', LLM_C, LLM_FILL, 58)
    elif tag == 'BOTH':
        pill(d, x + W - 164, y + 25, 'LLM + ENGINE', TEAL, 'white', 144)
    else:
        pill(d, x + W - 108, y + 25, 'ENGINE', TEAL, ENG_FILL, 88)
    d.text(x + 21, y + 98, title, 25, color, True, max_width=W - 42)
    for i, line in enumerate(lines):
        d.text(x + 21, y + 136 + i * 27, line, 19, INK, max_width=W - 40)


def render():
    d = Diagram(1800, 900, 'One wave in Rippletown',
                'Seven steps of a wave: scheduled events, state endings, concurrent agent turns, routing by '
                'start-of-wave positions, applying requests, advancing the clock and contact processes.')
    d.text(70, 62, 'One wave in Rippletown', 34, INK, True)
    d.text(72, 100, 'Language-model steps sit inside an engine loop that fixes their order, the positions used and the time',
           21, MUTED, max_width=1620)

    step(d, XS[0], ROW_A, 1, 'Scheduled events',
         ['Fire at their clock time', 'Deliver daily-routine cues', 'Cued agents join the wave'], 'ENGINE')
    step(d, XS[1], ROW_A, 2, 'States end',
         ['Sleep, private activity, travel', 'Agent told the state is over', 'and what it missed'], 'ENGINE')
    step(d, XS[2], ROW_A, 3, 'Agent turns',
         ['All participants at once', 'Speech, action and requests', 'Memory compressed as context fills'],
         'LLM', LLM_C, LLM_FILL)
    step(d, XS[3], ROW_A, 4, 'Route messages',
         ['By start-of-wave positions', 'Addressed, overheard, seen', 'Held while in a state'], 'ENGINE')

    step(d, XS[3], ROW_B, 5, 'Apply requests',
         ['Move one step, bring others', 'Appearance and states', 'Within spatial, state rules'], 'ENGINE')
    step(d, XS[2], ROW_B, 6, 'Advance the clock',
         ['LLM estimates the minutes', 'Engine bounds them by the', "schedule and agents' states"], 'BOTH')
    step(d, XS[1], ROW_B, 7, 'Contact processes',
         ['For example, infection', 'Start-of-wave grouping', "credited with the wave's time"],
         'ENGINE', ORANGE, ORANGE_FILL)

    ym_a, ym_b = ROW_A + H // 2, ROW_B + H // 2
    for x in XS[:3]:
        d.arrow([(x + W, ym_a), (x + 415, ym_a)], TEAL)
    d.arrow([(XS[3] + W // 2, ROW_A + H), (XS[3] + W // 2, ROW_B)], TEAL)
    for x in (XS[3], XS[2]):
        d.arrow([(x, ym_b), (x - 45, ym_b)], TEAL)

    # loop back to the next wave: up into the right part of step 1, clear of the label
    lx = XS[0] + W - 50
    d.arrow([(XS[1], ym_b), (lx, ym_b), (lx, ROW_A + H)], TEAL)
    d.text(XS[0], ROW_B + 40, 'Next wave', 22, TEAL, True)
    for i, line in enumerate(['Agents addressed in this wave,', 'plus those cued by events,',
                              'released from a state or', 're-invoked by the scheduler']):
        d.text(XS[0], ROW_B + 74 + i * 26, line, 18, MUTED, max_width=lx - XS[0] - 24)

    yl = ROW_B + H + 70
    d.rect(70, yl - 34, 1620, 2, RULE, RULE, 1, 1)
    pill(d, 70, yl, 'LLM', LLM_C, LLM_FILL, 58)
    d.text(140, yl + 21, 'generated by the language model', 18, MUTED)
    pill(d, 450, yl, 'ENGINE', TEAL, ENG_FILL, 88)
    d.text(550, yl + 21, 'explicit engine rule', 18, MUTED)
    pill(d, 790, yl, 'LLM + ENGINE', TEAL, 'white', 144)
    d.text(946, yl + 21, 'model proposes, engine bounds', 18, MUTED)
    d.text(70, yl + 66, 'Ongoing states limit turn scheduling and message delivery; '
           'direct addressing can interrupt sleep or private activity.', 18, MUTED, max_width=1620)
    d.save('figure1-wave-en')


if __name__ == '__main__':
    render()
    print('Rendered figure1-wave-en.svg and figure1-wave-en.png')
